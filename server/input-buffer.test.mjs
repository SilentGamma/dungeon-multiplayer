import assert from 'node:assert/strict';
import {createInputBuffer} from './public/input-buffer.mjs';
import {Session} from './session.mjs';
const sent=[];
const buffer=createInputBuffer((message,signal)=>{sent.push({message,signal});return new Promise(()=>{});},{maxInFlight:2,timeoutMs:10000});
buffer.push({seq:1});await Promise.resolve();
buffer.push({seq:2});await Promise.resolve();
assert.equal(sent.length,2,'a slow request must not block the newest input');
buffer.push({seq:3});await Promise.resolve();
assert(sent[0].signal.aborted,'oldest request is removed when the buffer is full');
assert(!sent[2].signal.aborted);
buffer.close();assert(sent[1].signal.aborted&&sent[2].signal.aborted);
const session=new Session({code:'1'});session.join({id:'p',name:'Player'});session.start('p');
const player=session.run.players[0];
assert(session.input('p',{seq:2,holding:true,attack:true,sentAt:Date.now()}));
assert(!session.input('p',{seq:1,holding:false,sentAt:Date.now()}),'out-of-order release is discarded');
assert(player.holding&&player.usingAttack);
assert(session.input('p',{seq:3,holding:false,sentAt:Date.now()-2000}),'late release clears held state');
assert(!player.holding&&!player.usingAttack,'late release cancels rather than executing an attack');
assert(!session.input('p',{seq:4,holding:true,attack:true,sentAt:Date.now()-2000}),'stale press is discarded');
assert(!player.holding);
assert(session.input('p',{seq:5,holding:true,attack:true,sentAt:Date.now()}));
console.log('PASS: bounded concurrent input, stale and out-of-order actions, and safe late release');
